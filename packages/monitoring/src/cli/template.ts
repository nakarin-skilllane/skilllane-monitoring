import type { ScanResult } from './scan'

const RULES = `/*
 * Error catalog of this app for skilllane-monitoring. The SDK reads this file at start
 * (no import needed) and looks here before its built-in table.
 *
 * Rules
 *  - key: the app's error code (string or number), or a name for messageMatch entries
 *  - hint: ≤ 30 characters (≤ 40 with dependency), English, constant: it groups errors,
 *          so never put changing values in it. Required: entries without a hint are skipped.
 *  - detail: ≤ 200 characters: what probably happened
 *  - howToFix: ≤ 200 characters: what to do about it
 *  - category: bug | input | data | dependency | config   (who has to act)
 *  - level: warn | error   (warn for the caller's mistakes; a 5xx response still logs error)
 *  - messageMatch: RegExp for errors that carry no code
 *  - no personal data anywhere in this file
 *  Breaking a rule never stops the app: a long text is cut with "…", an unknown value is
 *  ignored, and one warning at start lists what was changed. Run
 *  \`pnpm skilllane-monitoring errors check\` to see it before deploying.
 *
 * Removing skilllane-monitoring: \`pnpm skilllane-monitoring uninstall\` (or delete this
 * folder by hand; nothing imports it).
 */
`

function constantName(message: string, used: Set<string>): string {
  const base =
    message
      .toUpperCase()
      .replace(/[^A-Z0-9]+/g, '_')
      .replace(/^_|_$/g, '') || 'MESSAGE'
  let name = /^[0-9]/.test(base) ? `M_${base}` : base
  for (let i = 2; used.has(name); i++) name = `${base}_${i}`
  used.add(name)
  return name
}

function escapeRegExp(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')
}

export function renderCatalogFile(scan: ScanResult): string {
  const used = new Set<string>([...scan.errorCodes, ...scan.loggerCodes])
  const lines: string[] = []
  for (const code of [...scan.errorCodes, ...scan.loggerCodes]) {
    const key = /^[A-Za-z_][A-Za-z0-9_]*$/.test(code) ? code : `'${code}'`
    lines.push(`  ${key}: { hint: '', detail: '', howToFix: '' },`)
  }
  for (const { message, count } of scan.repeatedMessages) {
    const name = constantName(message, used)
    lines.push(
      `  ${name}: { messageMatch: /^${escapeRegExp(message)}$/, hint: '', detail: '', howToFix: '' }, // seen ${count} times`,
    )
  }
  return `${RULES}
// Types only, removed at build: lets Nest exceptions take { code, howToFix, … }
// in apps that load the SDK with NODE_OPTIONS and never import it.
import type {} from 'skilllane-monitoring'

const catalog = {
${lines.join('\n')}
}

/** The codes above as constants: throw new AppError(AppErrorCode.X, …), this.logger.error('…', { code: AppErrorCode.X }). */
export const AppErrorCode = {} as { [K in keyof typeof catalog as \`\${K & (string | number)}\`]: \`\${K & (string | number)}\` }
for (const code of Object.keys(catalog)) (AppErrorCode as Record<string, string>)[code] = code

export default {
  errors: {
    // Where the app keeps its code on an error. Unset: the SDK reads err.code and Nest's errorCode.
    // codeOf: (err: any) => err.errorCode,
    catalog,
  },
}
`
}

export const LOG_MARKER = '// generated by skilllane-monitoring errors init'

/** log.ts next to the catalog: the app imports `log` from here, not from the SDK. */
export function renderLogFile(): string {
  return `${LOG_MARKER}
/*
 * \`log\` of skilllane-monitoring: new Logger(Class.name) without declaring it. Each line
 * goes under the class that called it.
 *
 *   import { log } from '../skilllane-monitoring/log'
 *   log.error('Evaluate the exam failed', err)
 *
 * Import it from this file, not from the package: \`pnpm skilllane-monitoring uninstall\`
 * turns this file into Nest's Logger, and the app still builds without the SDK.
 */
export { log } from 'skilllane-monitoring'
`
}

/** log.ts after uninstall: Nest's Logger stands in for the SDK's `log`. */
export function renderNestLogFile(): string {
  return `/*
 * skilllane-monitoring was removed: Nest's own Logger stands in for its \`log\`.
 * Lines no longer name the class that called; use new Logger(Class.name) where it matters.
 */
import { Logger } from '@nestjs/common'

export const log = new Logger()
`
}
