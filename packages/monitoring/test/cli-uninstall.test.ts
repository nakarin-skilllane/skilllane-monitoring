import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  writeFileSync,
} from 'fs'
import { tmpdir } from 'os'
import { join } from 'path'
import { describe, expect, it } from 'vitest'
import { planUninstall, uninstall } from '../src/cli/uninstall'

function project(files: Record<string, string>): string {
  const root = mkdtempSync(join(tmpdir(), 'slm-uninstall-'))
  writeFileSync(
    join(root, 'package.json'),
    '{"name":"app","dependencies":{"skilllane-monitoring":"^0.3.0"}}',
  )
  for (const [rel, body] of Object.entries(files)) {
    mkdirSync(join(root, rel, '..'), { recursive: true })
    writeFileSync(join(root, rel), body)
  }
  return root
}

const APP = {
  'pnpm-lock.yaml': '',
  'src/skilllane-monitoring/errors.ts':
    'export default { errors: { catalog: {} } }',
  'src/skilllane-monitoring/README.md':
    '<!-- generated by skilllane-monitoring errors init -->\n# ...',
  'src/main.ts': `// CI trigger 8\nimport 'skilllane-monitoring/register'\nimport './instrumentation'\n`,
  'src/instrumentation.ts': `import 'dotenv/config'\nimport 'skilllane-monitoring/register'\n\nif (process.env.X) require('./x')\n`,
  Dockerfile: `ENV NODE_OPTIONS="--require skilllane-monitoring/register"\n`,
}

function run(): { calls: string[][]; fn: (cmd: string[]) => number } {
  const calls: string[][] = []
  return {
    calls,
    fn: (cmd) => {
      calls.push(cmd)
      return 0
    },
  }
}

describe('planUninstall', () => {
  it('lists the catalog, the register lines, outside references and the pnpm command', () => {
    const root = project(APP)
    const plan = planUninstall({ cwd: root })
    expect(plan.deleteFiles).toEqual([
      'src/skilllane-monitoring/errors.ts',
      'src/skilllane-monitoring/README.md',
    ])
    expect(plan.deleteDirs).toEqual(['src/skilllane-monitoring'])
    expect(plan.lineEdits).toEqual([
      {
        file: 'src/instrumentation.ts',
        line: 2,
        text: `import 'skilllane-monitoring/register'`,
      },
      {
        file: 'src/main.ts',
        line: 2,
        text: `import 'skilllane-monitoring/register'`,
      },
    ])
    expect(plan.blockers).toEqual([])
    expect(plan.outside).toEqual([
      {
        file: 'Dockerfile',
        line: 1,
        text: 'ENV NODE_OPTIONS="--require skilllane-monitoring/register"',
      },
    ])
    expect(plan.removeCommand).toEqual([
      'pnpm',
      'remove',
      'skilllane-monitoring',
    ])
  })

  it('keeps a README the team wrote, the folder with it, and picks npm without a pnpm lock', () => {
    const root = project({
      'src/skilllane-monitoring/errors.ts': '',
      'src/skilllane-monitoring/README.md': '# ours',
      'package-lock.json': '{}',
    })
    const plan = planUninstall({ cwd: root })
    expect(plan.deleteFiles).toEqual(['src/skilllane-monitoring/errors.ts'])
    expect(plan.deleteDirs).toEqual([])
    expect(plan.removeCommand).toEqual([
      'npm',
      'uninstall',
      'skilllane-monitoring',
    ])
  })

  it('treats other imports as blockers, but not plain mentions', () => {
    const root = project({
      'src/app.module.ts': `import { LoggingModule } from 'skilllane-monitoring'\n`,
      'src/jobs.ts': `const { tracked } = require('skilllane-monitoring')\n`,
      'src/notes.ts': `// see skilllane-monitoring for the format\nconst name = 'skilllane-monitoring'\n`,
    })
    expect(planUninstall({ cwd: root }).blockers).toEqual([
      {
        file: 'src/app.module.ts',
        line: 1,
        text: `import { LoggingModule } from 'skilllane-monitoring'`,
      },
      {
        file: 'src/jobs.ts',
        line: 1,
        text: `const { tracked } = require('skilllane-monitoring')`,
      },
    ])
  })
})

describe('planUninstall and AppErrorCode', () => {
  it('blocks on app files that use AppErrorCode from the catalog', () => {
    const root = project({
      ...APP,
      'src/orders.ts': `import { AppErrorCode } from './skilllane-monitoring/errors'\nthrow new Error(AppErrorCode.ORDER_PAID)\n`,
      'src/notes.ts': `const AppErrorCodes = 1\n`,
    })
    const blockers = planUninstall({ cwd: root }).blockers
    expect(blockers.map((b) => `${b.file}:${b.line}`)).toEqual([
      'src/orders.ts:1',
      'src/orders.ts:2',
    ])
  })

  it('tells to replace AppErrorCode.X with the string first', async () => {
    const root = project({
      ...APP,
      'src/orders.ts': `x(AppErrorCode.ORDER_PAID)\n`,
    })
    const out: string[] = []
    const status = await uninstall({
      cwd: root,
      yes: true,
      out: (l: string) => out.push(l),
      run: () => 0,
    } as any)
    expect(status).toBe(1)
    expect(out.join('\n')).toMatch(/AppErrorCode\.X.*string/)
  })
})

describe('uninstall', () => {
  it('removes the catalog, the register lines, then runs the package manager', async () => {
    const root = project(APP)
    const r = run()
    expect(
      await uninstall({ cwd: root, yes: true, run: r.fn, out: () => {} }),
    ).toBe(0)
    expect(existsSync(join(root, 'src/skilllane-monitoring'))).toBe(false)
    expect(readFileSync(join(root, 'src/main.ts'), 'utf8')).toBe(
      `// CI trigger 8\nimport './instrumentation'\n`,
    )
    expect(readFileSync(join(root, 'src/instrumentation.ts'), 'utf8')).toBe(
      `import 'dotenv/config'\n\nif (process.env.X) require('./x')\n`,
    )
    expect(readFileSync(join(root, 'Dockerfile'), 'utf8')).toContain(
      'NODE_OPTIONS',
    )
    expect(r.calls).toEqual([['pnpm', 'remove', 'skilllane-monitoring']])
  })

  it('stops on other imports unless --force', async () => {
    const root = project({
      ...APP,
      'src/app.module.ts': `import { LoggingModule } from 'skilllane-monitoring'\n`,
    })
    const r = run()
    const out: string[] = []
    expect(
      await uninstall({
        cwd: root,
        yes: true,
        run: r.fn,
        out: (l) => out.push(l),
      }),
    ).toBe(1)
    expect(r.calls).toEqual([])
    expect(existsSync(join(root, 'src/skilllane-monitoring/errors.ts'))).toBe(
      true,
    )
    expect(out.join('\n')).toContain('src/app.module.ts:1')
    expect(
      await uninstall({
        cwd: root,
        yes: true,
        force: true,
        run: r.fn,
        out: () => {},
      }),
    ).toBe(0)
    expect(r.calls).toHaveLength(1)
  })

  it('does nothing when the answer is not yes', async () => {
    const root = project(APP)
    const r = run()
    expect(
      await uninstall({
        cwd: root,
        ask: async () => false,
        run: r.fn,
        out: () => {},
      }),
    ).toBe(1)
    expect(existsSync(join(root, 'src/skilllane-monitoring/errors.ts'))).toBe(
      true,
    )
    expect(readFileSync(join(root, 'src/main.ts'), 'utf8')).toContain(
      'skilllane-monitoring/register',
    )
    expect(r.calls).toEqual([])
  })

  it('returns the package manager exit code', async () => {
    const root = project(APP)
    expect(
      await uninstall({ cwd: root, yes: true, run: () => 3, out: () => {} }),
    ).toBe(3)
  })
})
