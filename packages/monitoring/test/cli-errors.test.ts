import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  writeFileSync,
} from 'fs'
import { tmpdir } from 'os'
import { join } from 'path'
import ts from 'typescript'
import { describe, expect, it } from 'vitest'
import { symlinkSync } from 'fs'
import { errorsCheck } from '../src/cli/errors-check'
import { errorsInit } from '../src/cli/errors-init'
import { runCli } from '../src/cli/index'
import { scanSource } from '../src/cli/scan'
import { renderCatalogFile } from '../src/cli/template'

function project(files: Record<string, string>): string {
  const root = mkdtempSync(join(tmpdir(), 'slm-cli-'))
  writeFileSync(join(root, 'package.json'), '{"name":"app"}')
  for (const [rel, body] of Object.entries(files)) {
    mkdirSync(join(root, rel, '..'), { recursive: true })
    writeFileSync(join(root, rel), body)
  }
  return root
}

const SOURCES = {
  'src/a.exception.ts': `export class A extends BaseException { readonly errorCode = 'STUDENT_LEAVE_SCHOOL' }`,
  'src/b.exception.ts': `super(message, 409, { errorCode: 'EXAM_SHARE_REQUIRES_QUESTION_CASCADE' })`,
  'src/users.service.ts': [
    `throw new NotFoundException('User not found')`,
    `throw new NotFoundException('User not found')`,
    `throw new BadRequestException("User not found")`,
    `throw new BadRequestException('Once only')`,
    `this.logger.error('Import failed', { code: 'E1001' })`,
  ].join('\n'),
  'src/users.service.spec.ts': `throw new NotFoundException('User not found')`,
}

describe('scanSource', () => {
  it('finds errorCode literals, repeated throw messages and logger codes, skipping tests', () => {
    const root = project(SOURCES)
    expect(scanSource(join(root, 'src'), 3)).toEqual({
      errorCodes: [
        'EXAM_SHARE_REQUIRES_QUESTION_CASCADE',
        'STUDENT_LEAVE_SCHOOL',
      ],
      repeatedMessages: [{ message: 'User not found', count: 3 }],
      loggerCodes: ['E1001'],
    })
  })
})

describe('errors init', () => {
  it('writes the catalog with the rules, the found codes and messages', () => {
    const root = project(SOURCES)
    const out: string[] = []
    expect(
      errorsInit({ cwd: root, minRepeat: 3, out: (l) => out.push(l) }),
    ).toBe(0)
    const file = readFileSync(
      join(root, 'src/skilllane-monitoring/errors.ts'),
      'utf8',
    )
    expect(file).toContain('hint: ≤ 30')
    expect(file).toContain(
      `  STUDENT_LEAVE_SCHOOL: { hint: '', detail: '', howToFix: '' },`,
    )
    expect(file).toContain(`  E1001: { hint: '', detail: '', howToFix: '' },`)
    expect(file).toContain(
      `  USER_NOT_FOUND: { messageMatch: /^User not found$/, hint: '', detail: '', howToFix: '' }, // seen 3 times`,
    )
    expect(file).toContain('export default {')
    expect(file).toContain('const catalog = {')
    expect(file).toContain('export const AppErrorCode = ')
    expect(file).toContain('    catalog,')
    expect(out.join('\n')).toContain('src/skilllane-monitoring/errors.ts')
    const readme = readFileSync(
      join(root, 'src/skilllane-monitoring/README.md'),
      'utf8',
    )
    expect(readme.split('\n')[0]).toBe(
      '<!-- generated by skilllane-monitoring errors init -->',
    )
    expect(readme).toContain('SKILLLANE_MONITORING_ERRORS_FILE_PATH')
    expect(readme).toContain('pnpm skilllane-monitoring uninstall')
  })

  it('exports AppErrorCode with the catalog keys', async () => {
    const file = renderCatalogFile({
      errorCodes: ['ORDER_ALREADY_PAID'],
      loggerCodes: ['1701'],
      repeatedMessages: [],
    } as any)
    const js = ts.transpileModule(file, {
      compilerOptions: { module: ts.ModuleKind.CommonJS },
    }).outputText
    const mod: any = { exports: {} }
    new Function('module', 'exports', js)(mod, mod.exports)
    // The type import leaves nothing at run time: the catalog loads without the SDK.
    expect(js).not.toContain('require(')
    expect(mod.exports.AppErrorCode).toEqual({
      ORDER_ALREADY_PAID: 'ORDER_ALREADY_PAID',
      1701: '1701',
    })
    expect(Object.keys(mod.exports.default.errors.catalog)).toEqual([
      '1701',
      'ORDER_ALREADY_PAID',
    ])
  })

  it('compiles for apps on target es2017 (no es2019 APIs)', () => {
    const file = renderCatalogFile({
      errorCodes: ['ORDER_ALREADY_PAID'],
      loggerCodes: ['1701'],
      repeatedMessages: [{ message: 'User not found', count: 3 }],
    } as any)
    const options: ts.CompilerOptions = {
      strict: true,
      target: ts.ScriptTarget.ES2017,
      lib: ['lib.es2017.d.ts'],
      noEmit: true,
      skipLibCheck: true,
      types: [],
      // The app has the SDK installed; here a stub stands in for it.
      baseUrl: '.',
      paths: { 'skilllane-monitoring': ['sdk-stub.d.ts'] },
    }
    const host = ts.createCompilerHost(options)
    const read = host.getSourceFile.bind(host)
    host.getSourceFile = (name, lang, ...rest) =>
      name === 'catalog.ts'
        ? ts.createSourceFile(name, file, lang)
        : name.endsWith('sdk-stub.d.ts')
          ? ts.createSourceFile(name, 'export {}', lang)
          : read(name, lang, ...rest)
    const fileExists = host.fileExists.bind(host)
    host.fileExists = (name) =>
      name === 'catalog.ts' ||
      name.endsWith('sdk-stub.d.ts') ||
      fileExists(name)
    const program = ts.createProgram(['catalog.ts'], options, host)
    const diagnostics = ts.getPreEmitDiagnostics(program)
    expect(
      diagnostics.map((d) =>
        ts.flattenDiagnosticMessageText(d.messageText, '\n'),
      ),
    ).toEqual([])
  })

  it('never overwrites a README the team wrote', () => {
    const root = project({ 'src/skilllane-monitoring/README.md': 'ours' })
    errorsInit({ cwd: root, out: () => {} })
    expect(
      readFileSync(join(root, 'src/skilllane-monitoring/README.md'), 'utf8'),
    ).toBe('ours')
    expect(existsSync(join(root, 'src/skilllane-monitoring/errors.ts'))).toBe(
      true,
    )
  })

  it('never overwrites an existing file', () => {
    const root = project({ 'src/skilllane-monitoring/errors.ts': 'keep me' })
    expect(errorsInit({ cwd: root, out: () => {} })).toBe(0)
    expect(
      readFileSync(join(root, 'src/skilllane-monitoring/errors.ts'), 'utf8'),
    ).toBe('keep me')
  })

  it('writes to --path with a README there and tells the SKILLLANE_MONITORING_ERRORS_FILE_PATH line', () => {
    const root = project({ 'src/main.ts': '' })
    const out: string[] = []
    errorsInit({
      cwd: root,
      path: 'src/common/config/monitoring-errors.ts',
      out: (l) => out.push(l),
    })
    expect(
      existsSync(join(root, 'src/common/config/monitoring-errors.ts')),
    ).toBe(true)
    const readme = readFileSync(
      join(root, 'src/common/config/README.md'),
      'utf8',
    )
    expect(readme).toContain(
      'SKILLLANE_MONITORING_ERRORS_FILE_PATH=src/common/config/monitoring-errors.ts',
    )
    expect(out).toContain(
      'add to .env: SKILLLANE_MONITORING_ERRORS_FILE_PATH=src/common/config/monitoring-errors.ts',
    )
  })
})

function linkTypescript(root: string): void {
  // the project under test needs its own typescript, like a real app (tests run from packages/monitoring)
  mkdirSync(join(root, 'node_modules'), { recursive: true })
  symlinkSync(
    join(process.cwd(), 'node_modules/typescript'),
    join(root, 'node_modules/typescript'),
    'dir',
  )
}

describe('errors check', () => {
  it('passes a valid catalog and warns about codes the source uses but the catalog lacks', () => {
    const root = project({
      ...SOURCES,
      'src/skilllane-monitoring/errors.ts': `export default { errors: { catalog: { STUDENT_LEAVE_SCHOOL: { hint: 'Student left school' } } } }`,
    })
    linkTypescript(root)
    const out: string[] = []
    expect(errorsCheck({ cwd: root, out: (l) => out.push(l) })).toBe(0)
    expect(out.join('\n')).toContain(
      'warning EXAM_SHARE_REQUIRES_QUESTION_CASCADE: used in src/ but not in the catalog',
    )
    expect(out.join('\n')).toContain(
      'warning E1001: used in src/ but not in the catalog',
    )
  })

  it('accepts a RegExp made by the transpiled file (another realm)', () => {
    const root = project({
      'src/skilllane-monitoring/errors.ts': `export default { errors: { catalog: { USER_NOT_FOUND: { messageMatch: /^User not found$/, hint: 'User not found' } } } }`,
    })
    linkTypescript(root)
    const out: string[] = []
    expect(errorsCheck({ cwd: root, out: (l) => out.push(l) })).toBe(0)
    expect(out.join('\n')).not.toContain('messageMatch')
    expect(out.join('\n')).toContain('1 codes, 0 errors')
  })

  it('fails on rule errors', () => {
    const root = project({
      'src/skilllane-monitoring/errors.ts': `export default { errors: { catalog: { E1: { hint: '${'x'.repeat(31)}' } } } }`,
    })
    linkTypescript(root)
    const out: string[] = []
    expect(errorsCheck({ cwd: root, out: (l) => out.push(l) })).toBe(1)
    expect(out.join('\n')).toContain(
      'error E1: hint is longer than 30 characters; cut',
    )
  })

  it('fails when the file is missing', () => {
    const root = project({})
    expect(errorsCheck({ cwd: root, out: () => {} })).toBe(1)
  })
})

describe('cli', () => {
  it('routes errors init / check and rejects unknown commands', () => {
    const root = project({})
    expect(runCli(['errors', 'init'], root, () => {})).toBe(0)
    expect(runCli(['nope'], root, () => {})).toBe(64)
  })

  it('reads --path and --min-repeat', () => {
    const root = project({})
    expect(
      runCli(
        ['errors', 'init', '--path', 'src/x/errors.ts', '--min-repeat', '2'],
        root,
        () => {},
      ),
    ).toBe(0)
    expect(existsSync(join(root, 'src/x/errors.ts'))).toBe(true)
  })
})
