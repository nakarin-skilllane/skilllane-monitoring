import { readFileSync, writeFileSync } from 'fs'
import { join } from 'path'
import { describe, expect, it } from 'vitest'
import { lookupHint } from '../src/errors/hints'
import { type ErrorPattern, PATTERN_GROUPS } from '../src/errors/patterns'

const FILE = join(__dirname, '../src/errors/error-codes.ts')
/** For keys that start with a digit. */
const PREFIX: Record<string, string> = { postgres: 'PG', mysql: 'MY' }

function identifier(group: string, key: string): string {
  const name = key.replace(/[^A-Za-z0-9_$]/g, '_')
  return /^[0-9]/.test(name) ? `${PREFIX[group] ?? 'E'}_${name}` : name
}

function render(): string {
  const out = [
    '// Generated by `pnpm gen:codes` from src/errors/patterns. Do not edit.',
    "import { errorCode } from './error-code'",
    '',
    '/** Every code of the built-in hint table, by file: `ErrorCode.smtp.ECONNECTION`. */',
    'export const ErrorCode = {',
  ]
  for (const [group, patterns] of Object.entries(PATTERN_GROUPS)) {
    const byKey = new Map<string, ErrorPattern>()
    for (const pattern of patterns) {
      const seen = byKey.get(pattern.key)
      // the same key twice in one file: the dependency-scoped one is the precise one
      if (!seen || (!seen.dependency && pattern.dependency)) {
        byKey.set(pattern.key, pattern)
      }
    }
    const names = new Map<string, string>()
    out.push(`  ${group}: {`)
    for (const pattern of byKey.values()) {
      const name = identifier(group, pattern.key)
      const taken = names.get(name)
      if (taken)
        throw new Error(
          `${group}: ${taken} and ${pattern.key} both become ${name}`,
        )
      names.set(name, pattern.key)
      const args = pattern.dependency
        ? `'${pattern.key}', '${pattern.dependency}'`
        : `'${pattern.key}'`
      out.push(`    ${name}: errorCode(${args}),`)
    }
    out.push('  },')
  }
  out.push('} as const', '')
  return out.join('\n')
}

describe('ErrorCode', () => {
  it('matches the hint table (pnpm gen:codes rewrites it)', () => {
    const expected = render()
    if (process.env.UPDATE_ERROR_CODES) writeFileSync(FILE, expected)
    expect(readFileSync(FILE, 'utf8')).toBe(expected)
  })

  it('names codes that are not identifiers and keeps the real code', async () => {
    const { ErrorCode } = await import('../src/errors/error-codes')
    expect(ErrorCode.oracle.ORA_00001.code).toBe('ORA-00001')
    expect(ErrorCode.postgres.PG_23505.code).toBe('23505')
    expect(ErrorCode.redis.ECONNREFUSED.dependency).toBe('redis')
    expect(ErrorCode.oracle.NJS_040.dependency).toBe('oracle')
  })

  it('every code resolves to its own pattern', async () => {
    const { ErrorCode } = await import('../src/errors/error-codes')
    for (const group of Object.values(ErrorCode)) {
      for (const ref of Object.values(group)) {
        const hint = lookupHint({ code: ref.code, dependency: ref.dependency })
        expect(hint?.key, ref.code).toBe(ref.code)
      }
    }
  })
})
